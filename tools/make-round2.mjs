const 행 = [];

for (const [sid, round, 목적, 지시] of 계획) {
  for (let turn = 1; turn <= 5; turn++) {
    const r = Object.fromEntries(컬럼.map(c => [c, '']));
    r.seed_id = sid;
    r.목적 = 목적;
    r.round = String(round);
    r.turn = String(turn);
    if (turn === 1) r.입력질문 = 질문[sid];
    r.답변원문파일 = `data/raw/round2/${sid}-r${round}.txt`;
    if (turn === 1) r.메모 = 지시;
    행.push(r);
  }
}

// 🔴 이미 관측을 기록한 파일을 덮어쓰지 않는다.
// 관측은 질문 한도를 태워 얻은 것이고 비결정성 때문에 재현이 안 된다.
const OUT = 'data/observations-round2.csv';
if (fs.existsSync(OUT) && /(,정답,|,부분,|,오답,|,거절,|,무응답,)/.test(fs.readFileSync(OUT, 'utf8'))) {
  console.error(`${OUT} 에 이미 기록된 관측이 있어 생성을 중단한다. 정말 새로 만들려면 파일을 먼저 옮겨 둘 것.`);
  process.exit(1);
}
fs.writeFileSync(OUT, writeCsv(행, 컬럼));
